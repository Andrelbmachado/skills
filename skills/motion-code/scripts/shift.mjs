// Reaplica as janelas de script.json ao timing.json existente sem nova síntese/whisper: start = janela[0] + lead; palavras acompanham o deslocamento.
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from './lib.mjs'
const S = JSON.parse(fs.readFileSync(path.join(ROOT, 'script.json'), 'utf8')), T = JSON.parse(fs.readFileSync(path.join(ROOT, 'timing.json'), 'utf8'))
for (const l of T.lines) {
  const sl = S.lines.find(x => x.id === l.id), ns = +(sl.window[0] + sl.lead).toFixed(3), d = ns - l.start
  l.start = ns; l.words.forEach(w => { w.t0 = +(w.t0 + d).toFixed(3); w.t1 = +(w.t1 + d).toFixed(3) })
}
T.duration = S.duration
fs.writeFileSync(path.join(ROOT, 'timing.json'), JSON.stringify(T, null, 1))
fs.writeFileSync(path.join(ROOT, 'src/timing.js'), '// generated by tools/tts.mjs (+shift.mjs)\nexport const TIMING = ' + JSON.stringify(T) + '\n')
console.log('shifted; duration', T.duration, T.lines.map(l => l.id + '@' + l.start).join(' '))
