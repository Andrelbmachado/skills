# Samples each hand-picked painting point (assets/art/points.json) as the mean colour of a small box
# around (u, v) — the colour the reel's "ball" shows — and writes src/art.js.
from PIL import Image
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = json.load(open(os.path.join(ROOT, 'assets/art/points.json')))
out = {}
for key, art in spec.items():
    im = Image.open(os.path.join(ROOT, 'assets/art', art['file'])).convert('RGB'); W, H = im.size
    pts = []
    for p in art['points']:
        r = int(W * p.get('r', 0.01))
        c = im.crop((int(p['u'] * W) - r, int(p['v'] * H) - r, int(p['u'] * W) + r, int(p['v'] * H) + r)).resize((1, 1), Image.BOX).getpixel((0, 0))
        pts.append({**p, 'rgb': '#%02X%02X%02X' % c})
        print(key, p['hue'], (p['u'], p['v']), pts[-1]['rgb'])
    out[key] = {**art, 'aspect': round(W / H, 4), 'points': pts}
open(os.path.join(ROOT, 'src/art.js'), 'w').write('// generated by tools/art-pick.py from assets/art/points.json\nexport const ART = ' + json.dumps(out, ensure_ascii=False, indent=1) + '\n')
